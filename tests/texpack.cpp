// a plain 32-bit DDS (A8R8G8B8) of the given pixels
std::vector<std::uint8_t> plain_dds(const std::vector<std::uint32_t> &px, std::uint32_t w, std::uint32_t h) {
    std::vector<std::uint8_t> d(128, 0);
    std::memcpy(d.data(), "DDS ", 4);
    const auto put = [&](std::size_t at, std::uint32_t v) { std::memcpy(d.data() + at, &v, 4); };
    put(4, 124), put(12, h), put(16, w), put(76, 32), put(80, 0x41), put(88, 32);
    put(92, 0x00ff0000), put(96, 0x0000ff00), put(100, 0x000000ff), put(104, 0xff000000);
    for (std::uint32_t p : px) {
        const std::uint32_t argb = (p & 0xff00ff00u) | (p & 0xff) << 16 | (p >> 16 & 0xff);
        for (int i = 0; i < 4; ++i) d.push_back(static_cast<std::uint8_t>(argb >> (8 * i)));
    }
    return d;
}
void write_file(const fs::path &p, const std::vector<std::uint8_t> &bytes) {
    std::ofstream out(p, std::ios::binary);
    out.write(reinterpret_cast<const char *>(bytes.data()), static_cast<std::streamsize>(bytes.size()));
}

bool read_tga(const std::string &path, std::vector<std::uint32_t> &out, std::uint32_t &w, std::uint32_t &h) {
    std::ifstream in(ps2::os::path(path), std::ios::binary);
    std::vector<std::uint8_t> b((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
    if (b.size() < 18 || b[2] != 2 || b[16] != 32) return false;
    w = b[12] | b[13] << 8, h = b[14] | b[15] << 8;
    const bool top = b[17] & 0x20;
    const std::size_t at = 18 + b[0];
    if (b.size() < at + static_cast<std::size_t>(w) * h * 4) return false;
    out.resize(static_cast<std::size_t>(w) * h);
    for (std::uint32_t y = 0; y < h; ++y)
        for (std::uint32_t x = 0; x < w; ++x) {
            const std::uint8_t *p = b.data() + at + (static_cast<std::size_t>(top ? y : h - 1 - y) * w + x) * 4;
            out[static_cast<std::size_t>(y) * w + x] = rgba(p[2], p[1], p[0], p[3]);
        }
    return true;
}

int truth(int argc, char **argv) {
    const std::string originals = argv[2], pack_dir = argv[3], matches = argv[4], cache = argc > 5 ? argv[5] : "";
    std::map<std::string, std::pair<std::string, bool>> expected;  // ours -> pack file, matched
    {
        std::ifstream in(ps2::os::path(matches));
        std::string line;
        while (std::getline(in, line)) {
            std::istringstream s(line);
            std::string ours, file, diff, verdict;
            std::getline(s, ours, '\t'), std::getline(s, file, '\t'), std::getline(s, diff, '\t'), std::getline(s, verdict, '\t');
            while (!verdict.empty() && (verdict.back() == '\r' || verdict.back() == ' ')) verdict.pop_back();
            expected[ours] = {file, verdict == "match"};
        }
    }
    Pack pack(pack_dir, cache);
    pack.scan();
    pack.build_index();
    std::printf("pack: %zu pictures, index %s in %llu ms\n", pack.file_count(), pack.index_from_file ? "read from thumbs.bin" : "made",
                static_cast<unsigned long long>(pack.index_ms));
    int same = 0, differ = 0, matched = 0, total = 0;
    double worst_ms = 0, all_ms = 0;
    for (const auto &e : fs::directory_iterator(ps2::os::path(originals))) {
        const std::string name = ps2::os::utf8(e.path().filename());
        if (name.size() < 5 || name.substr(name.size() - 4) != ".tga") continue;
        const std::string ours = name.substr(0, name.size() - 4);
        std::vector<std::uint32_t> px;
        std::uint32_t w = 0, h = 0;
        if (!read_tga(ps2::os::utf8(e.path()), px, w, h)) continue;
        const auto t0 = std::chrono::steady_clock::now();
        const Pack::Result r = pack.match(px.data(), w, h);
        const double ms = std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - t0).count();
        worst_ms = std::max(worst_ms, ms), all_ms += ms;
        ++total;
        const std::string got = r.file >= 0 ? ps2::os::utf8(fs::path(pack.file_name(r.file)).filename()) : "-";
        matched += r.file >= 0;
        const auto it = expected.find(ours);
        const std::string want = it == expected.end() ? "?" : it->second.second ? it->second.first : "-";
        if (got == want) ++same;
        else {
            ++differ;
            std::printf("DIFFERS %s: chose %s (%.2f), tex_match.py %s\n", ours.c_str(), got.c_str(), r.diff, want.c_str());
        }
    }
    std::printf("originals %d: %d matched, %d the same as tex_match.py, %d differ; matching %.1f ms in all, %.2f ms worst\n", total, matched, same, differ,
                all_ms, worst_ms);
    return differ ? 1 : 0;
}
